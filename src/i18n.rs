    #[test]
    fn test_all_rules_localized_in_all_languages() {
        let rules = default_clean_rules();
        for &lang in Language::all() {
            if lang == Language::Italian {
                continue;
            }
            for rule in &rules {
                let loc = lang.localize_rule(rule.id);
                assert!(
                    loc.is_some(),
                    "Missing localization for rule ID {} in {:?}",
                    rule.id,
                    lang
                );
            }
        }
    }

